import 'dart:io';

import 'package:flutter/foundation.dart';
import 'package:path_provider/path_provider.dart';

import '../../domain/browser/repositories.dart';

/// Tab previews as `<cache>/thumbs/<tabId>.jpg`. Cache, not data: the OS
/// may clear it, and a missing preview just shows the site placeholder.
class FileThumbnailStore implements ThumbnailStore {
  Directory? _dir;

  Future<Directory> _root() async {
    final d = _dir ??= Directory(
      '${(await getApplicationCacheDirectory()).path}${Platform.pathSeparator}thumbs',
    );
    await d.create(recursive: true);
    return d;
  }

  /// Tab ids are generated by Prism, but never trust them as paths.
  static bool _safe(String id) => RegExp(r'^[A-Za-z0-9_-]{1,64}$').hasMatch(id);

  Future<File?> _file(String id) async => _safe(id)
      ? File('${(await _root()).path}${Platform.pathSeparator}$id.jpg')
      : null;

  @override
  Future<Uint8List?> load(String tabId) async {
    final f = await _file(tabId);
    if (f == null || !f.existsSync()) return null;
    return f.readAsBytes();
  }

  @override
  Future<void> save(String tabId, Uint8List bytes) async {
    await (await _file(tabId))?.writeAsBytes(bytes, flush: false);
  }

  @override
  Future<void> delete(String tabId) async {
    final f = await _file(tabId);
    if (f != null && f.existsSync()) await f.delete();
  }

  @override
  Future<void> retainOnly(Set<String> tabIds) async {
    final root = await _root();
    await for (final e in root.list()) {
      final name = e.uri.pathSegments.last;
      final id = name.endsWith('.jpg')
          ? name.substring(0, name.length - 4)
          : '';
      if (!tabIds.contains(id)) await e.delete();
    }
  }
}

/// Tests and showcase: nothing on disk.
class MemoryThumbnailStore implements ThumbnailStore {
  final _m = <String, Uint8List>{};

  @override
  Future<Uint8List?> load(String tabId) async => _m[tabId];

  @override
  Future<void> save(String tabId, Uint8List bytes) async => _m[tabId] = bytes;

  @override
  Future<void> delete(String tabId) async => _m.remove(tabId);

  @override
  Future<void> retainOnly(Set<String> tabIds) async =>
      _m.removeWhere((k, _) => !tabIds.contains(k));
}
